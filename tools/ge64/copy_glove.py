#!/usr/bin/env python3
"""Copy Mario's closed right hand and right forearm geometry out of actors/mario/model.inc.c into a
standalone include for src/game/ge64.c, so the viewmodel glove doesn't depend on segment 0x04
(Mario's model segment, which isn't loaded on the title screen).

usage: copy_glove.py <sm64 repo root>
"""
import os, re, sys

root = sys.argv[1]
src = open(os.path.join(root, 'actors/mario/model.inc.c')).read()

def array(kind, name):
    m = re.search(r'(?:static )?const %s %s\[\] = \{.*?\n\};' % (kind, re.escape(name)), src, re.S)
    assert m, name
    return m.group(0)

out = ['// Generated by tools/ge64/copy_glove.py from actors/mario/model.inc.c. Do not edit.']
for dl, newdl in (('mario_right_hand_closed_dl', 'ge64_glove_dl'), ('mario_right_forearm_shared_dl', 'ge64_sleeve_dl')):
    body = array('Gfx', dl)
    vtx_names = sorted(set(re.findall(r'gsSPVertex\((\w+)', body)))
    for v in vtx_names:
        text = array('Vtx', v)
        text = re.sub(r'^(?:static )?const Vtx ' + v, 'static const Vtx ge64_' + v, text)
        out.append(text)
        body = body.replace(v, 'ge64_' + v)
    body = re.sub(r'^const Gfx ' + dl, 'static const Gfx ' + newdl, body)
    out.append(body)
open(os.path.join(root, 'src/game/ge64_glove.inc.h'), 'w').write('\n\n'.join(out) + '\n')
print('copied glove and sleeve')
