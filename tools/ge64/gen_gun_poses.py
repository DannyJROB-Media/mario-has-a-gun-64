#!/usr/bin/env python3
"""Write src/game/ge64_guns/poses.inc.h from the tuned pose data (view position and glove grip
point per gun, as worked out with glove_preview.py)."""
import json, sys
data = json.load(open(sys.argv[1]))
out = ['// Generated by tools/ge64/gen_gun_poses.py: first-person pose per gun.',
       '// viewPos: gun model origin in view space; grip: where Mario\'s glove sits, in GE model units.']
for name, r in data.items():
    p = r['pos3']; g = r['hand_grip']
    out.append('#define GE64_POSE_%s { %.2ff, %.2ff, %.2ff }, { %.1ff, %.1ff, %.1ff }' % ((name.upper(),) + tuple(p) + tuple(g)))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
