    (45, 'DROP_GUN', 100, 0x80),
    (27, 'RICO_8A', 90, 0x80), (28, 'RICO_8B', 90, 0x80), (29, 'RICO_8C', 90, 0x80), (30, 'RICO_8D', 90, 0x80),
    (35, 'RICO_5A', 90, 0x80), (36, 'RICO_5B', 90, 0x80), (37, 'RICO_5C', 90, 0x80), (38, 'RICO_5D', 90, 0x80),
    (39, 'RICO_6A', 90, 0x80), (40, 'RICO_6B', 90, 0x80), (41, 'RICO_6C', 90, 0x80), (42, 'RICO_6D', 90, 0x80),
