#!/usr/bin/env python3
"""Convert a GoldenEye first-person gun model (GE decomp assets/obseg/gun/<name>/Model.c) into an
SM64-compatible C include: RGBA16 textures, Vtx arrays, Fast3D display lists, a part table and the
rest position of every model matrix.

GE draws guns without the z-buffer, ordering faces with BSP nodes; here every part gets a z-buffered
render mode instead, so all BSP children are simply drawn. Matrix loads stay as segment 0x03
addresses (GE's per-model matrix array); the game points segment 0x03 at its own per-frame matrices
while drawing the gun.

The model data (textures, vertices, display lists) becomes its own ROM segment, bin/ge64_<id>.c,
linked at 0x0E000000 and loaded into the gun buffer on demand; the small part table that the game
code reads lives in an include for src/game/ge64.c.

usage: convert_ge_gun.py <ge gun dir name> <C identifier> <sm64 repo root>
"""
import os, sys, re, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ge_model import Model
from ge_texture import decode

from ge_texture import GE_DECOMP
GE_GUN_DIR = os.path.join(GE_DECOMP, 'assets', 'obseg', 'gun')
TMP = tempfile.mkdtemp(prefix='ge64_getex_')

# Bond's hand/sleeve textures in the GE pistol models; those parts are hidden (Mario's glove is drawn instead)
HAND_TEXTURES = {'IMAGE_1793', 'IMAGE_1794', 'IMAGE_1795', 'IMAGE_1796', 'IMAGE_1797', 'IMAGE_1798', 'IMAGE_1608'}

PASSTHROUGH = {
    'gsDPPipeSync', 'gsDPSetCombine', 'gsDPSetTextureLOD', 'gsDPSetTextureDetail', 'gsDPSetTextureFilter',
    'gsSPClearGeometryMode', 'gsSPSetGeometryMode', 'gsSPTexture', 'gsDPSetPrimColor', 'gsDPSetEnvColor',
    'gsDPSetCycleType', 'gsDPSetTexturePersp', 'gsDPSetTextureLUT', 'gsDPSetTextureConvert',
    'gsDPSetCombineKey', 'gsDPSetAlphaCompare', 'gsDPSetColorDither', 'gsDPSetAlphaDither',
}

def _avg(a, b):
    return tuple((a[i] + b[i] + 1) // 2 for i in range(4))

def add_shift(arg, extra):
    """Combine a tile shift (0: none, 1-10: coords >> n, 11-15: coords << (16-n)) with an extra >> extra."""
    if extra == 0:
        return arg
    s = 0 if arg == 'G_TX_NOLOD' else int(arg, 0)
    net = (-s if s <= 10 else 16 - s) - extra  # net exponent of the coordinate scale
    assert -10 <= net <= 5, (arg, extra)
    return str(16 - net if net > 0 else -net)

def log2(n):
    return max(0, (n - 1).bit_length())

def texture_alpha_kind(pix):
    alphas = set(p[3] for p in pix)
    if alphas <= {255}:
        return 'opaque'
    if alphas <= {0, 255}:
        return 'cutout'
    return 'blend'

def rgba16(p):
    r, g, b, a = p
    return ((r >> 3) << 11) | ((g >> 3) << 6) | ((b >> 3) << 1) | (1 if a >= 128 else 0)

def main(gun, ident, repo):
    m = Model(os.path.join(GE_GUN_DIR, gun, 'Model.c'))
    os.makedirs(TMP, exist_ok=True)
    header = '// Generated by tools/ge64/convert_ge_gun.py from the GoldenEye 007 decomp (%s). Do not edit.' % gun
    out = [header, '#include <ultra64.h>', '#include "macros.h"', '']
    meta = [header, '']

    # ---- textures
    tex_info = {}
    for name, w, h in m.textures:
        w, h, pix, f = decode(name, TMP)
        if w < 4 or h < 4:
            # Texture loads want at least a few texels; tile tiny (solid colour) textures up to 4x4
            nw, nh = max(w, 4), max(h, 4)
            pix = [pix[(y % h) * w + (x % w)] for y in range(nh) for x in range(nw)]
            w, h = nw, nh
        kind = texture_alpha_kind(pix)
        cname = 'ge64_%s_tex_%s' % (ident, name.replace('IMAGE_', '').lower())
        # TMEM holds 4KB. GE's originals are smaller formats (CI4/CI8/IA); as RGBA16/32 some exceed
        # that, and loading past the end of TMEM is undefined on the RDP (corruption or a hang on
        # hardware). Halve the larger axis until it fits; the tile shift scales the coordinates.
        sx = sy = 0
        while w * h * (4 if kind == 'blend' else 2) > 4096:
            if w >= h:
                pix = [_avg(pix[y * w + x], pix[y * w + x + 1]) for y in range(h) for x in range(0, w, 2)]
                w //= 2; sx += 1
            else:
                pix = [_avg(pix[y * w + x], pix[(y + 1) * w + x]) for y in range(0, h, 2) for x in range(w)]
                h //= 2; sy += 1
        # (kind stays as classified before scaling: averaging cutout edges must not turn it into RGBA32)
        tex_info[name] = (cname, w, h, kind, sx, sy)
        if kind == 'blend':
            # Soft alpha (muzzle flash glow) needs RGBA32; 32x32 still fits TMEM
            vals = [(r << 24) | (g << 16) | (b << 8) | a for r, g, b, a in pix]
            out.append('ALIGNED8 static u32 %s[] = { // %dx%d rgba32' % (cname, w, h))
            for i in range(0, len(vals), 8):
                out.append('    ' + ', '.join('0x%08X' % v for v in vals[i:i + 8]) + ',')
        else:
            vals = [rgba16(p) for p in pix]
            out.append('ALIGNED8 static u16 %s[] = { // %dx%d %s' % (cname, w, h, kind))
            for i in range(0, len(vals), 16):
                out.append('    ' + ', '.join('0x%04X' % v for v in vals[i:i + 16]) + ',')
        out.append('};')
    out.append('')

    # ---- vertices: GE Vertex has the same 16-byte layout as Vtx
    vtx_offsets = {}
    for name, rows in m.vertices.items():
        off = int(name.split('_0x')[1], 16)
        cname = 'ge64_%s_vtx_%x' % (ident, off)
        vtx_offsets[off] = (cname, len(rows))
        out.append('static Vtx %s[] = {' % cname)
        for x, y, z, flag, s, t, r, g, b, a in rows:
            out.append('    {{{ %d, %d, %d }, %d, { %d, %d }, { 0x%02X, 0x%02X, 0x%02X, 0x%02X }}},'
                       % (x, y, z, flag, s, t, r & 0xFF, g & 0xFF, b & 0xFF, a & 0xFF))
        out.append('};')
    out.append('')

    def vtx_ref(addr):
        seg, off = addr >> 24, addr & 0xFFFFFF
        assert seg == 5, hex(addr)
        for base, (cname, count) in vtx_offsets.items():
            if base <= off < base + count * 16:
                return '&%s[%d]' % (cname, (off - base) // 16)
        raise KeyError(hex(addr))

    # ---- display lists
    unknown = set()
    def convert_gfx(gname, translucent):
        lines = []
        cur_tex_kind = 'opaque'
        for cmd, args in m.gfx[gname]:
            # Only the base texture level is converted, so mipmapped parts must sample tile 0 only
            if cmd == 'gsDPSetTextureLOD':
                lines.append('gsDPSetTextureLOD(G_TL_TILE)')
                continue
            if cmd == 'gsSPTexture':
                args = [args[0], args[1], '0', args[3], args[4]]
            if cmd in PASSTHROUGH:
                lines.append('%s(%s)' % (cmd, ', '.join(args)))
            elif cmd == 'gsSPEndDisplayList':
                lines.append('gsSPEndDisplayList()')
            elif cmd == 'gsSPSetOtherMode':
                which, sft, ln, data = args
                if which == 'G_SETOTHERMODE_L' and int(sft, 0) == 3:
                    # GE renders guns without Z (BSP ordered); use z-buffered modes instead
                    if translucent:
                        lines.append('gsDPSetRenderMode(G_RM_AA_ZB_XLU_SURF, G_RM_AA_ZB_XLU_SURF2)')
                    else:
                        lines.append('gsDPSetRenderMode(G_RM_AA_ZB_OPA_SURF, G_RM_AA_ZB_OPA_SURF2)')
                else:
                    lines.append('%s(%s)' % (cmd, ', '.join(args)))
            elif cmd == 'gsSPMatrix':
                lines.append('gsSPMatrix(%s, %s)' % (args[0], args[1]))
            elif cmd == 'gsSPVertex':
                lines.append('gsSPVertex(%s, %s, %s)' % (vtx_ref(int(args[0], 0)), args[1], args[2]))
            elif cmd == 'gsSPUseTexture':
                cms, cmt, tile, shifts, shiftt, ttype, minlevel, detail, tex = args
                cname, w, h, kind, sx, sy = tex_info[tex]
                cur_tex_kind = kind
                siz = 'G_IM_SIZ_32b' if kind == 'blend' else 'G_IM_SIZ_16b'
                lines.append('gsDPLoadTextureBlock(%s, G_IM_FMT_RGBA, %s, %d, %d, 0, %s, %s, %d, %d, %s, %s)'
                             % (cname, siz, w, h, cms, cmt, log2(w), log2(h),
                                add_shift(shifts, sx), add_shift(shiftt, sy)))
            elif cmd in ('gsSP1Triangle', 'gsSP2Triangles', 'gsSP4Triangles'):
                nums = [int(a, 0) for a in args]
                if cmd == 'gsSP1Triangle':
                    tris = [nums[0:3]]
                elif cmd == 'gsSP2Triangles':
                    tris = [nums[0:3], nums[4:7]]
                else:
                    tris = [nums[0:3], nums[3:6], nums[6:9], nums[9:12]]
                for t in tris:
                    if t[0] == t[1] == t[2]:
                        continue  # GE pads TRI4 commands with degenerate triangles
                    lines.append('gsSP1Triangle(%d, %d, %d, 0x0)' % tuple(t))
            else:
                unknown.add(cmd)
                lines.append('/* unsupported: %s(%s) */ gsDPNoOp()' % (cmd, ', '.join(args)))
        return lines

    data_out = out

    # Walk the tree, collect parts with the switches that gate them
    switch_ids = []
    parts = []
    for node, depth, switches in m.walk():
        for s in switches:
            if s not in switch_ids:
                switch_ids.append(s)
        if node['op'] != 'DL':
            continue
        rec = m.dlrec(node['data'])
        for which, gname in (('primary', rec['primary']), ('secondary', rec['secondary'])):
            if gname is None:
                continue
            textures = [a[-1] for c, a in m.gfx[gname] if c == 'gsSPUseTexture']
            translucent = which == 'secondary' or any(tex_info[t][3] == 'blend' for t in textures)
            cname = 'ge64_%s_dl_%s' % (ident, gname.split('_0x')[1])
            if not any(p['dl'] == cname for p in parts):
                body = convert_gfx(gname, translucent)
                out.append('Gfx %s[] = {' % cname)
                meta.append('extern Gfx %s[];' % cname)
                out += ['    %s,' % l for l in body]
                out.append('};')
                parts.append(dict(dl=cname, switches=list(switches), translucent=translucent,
                                  hand=bool(textures) and set(textures) <= HAND_TEXTURES,
                                  textures=[t.replace('IMAGE_', '') for t in textures]))
    out.append('')

    # Part table: required switch mask (bit i = switch_ids[i] must be enabled)
    out = meta_out = meta
    out.append('// Switches (GE model switch records), bit order:')
    for i, s in enumerate(switch_ids):
        under = sorted(set(t for p in parts if s in p['switches'] for t in p['textures']))
        out.append('//   bit %d: %s (parts textured with %s)' % (i, s, ', '.join(under) or 'nothing'))
    flash_mask = 0
    for i, s in enumerate(switch_ids):
        under = [p for p in parts if s in p['switches']]
        if under and all(p['translucent'] for p in under):
            flash_mask |= 1 << i
    all_mask = (1 << len(switch_ids)) - 1
    out.append('#define GE64_%s_FLASH_SWITCHES 0x%04X' % (ident.upper(), flash_mask))
    out.append('#define GE64_%s_DEFAULT_SWITCHES 0x%04X' % (ident.upper(), all_mask & ~flash_mask))
    out.append('static const struct GeGunPart ge64_%s_parts[] = {' % ident)
    for p in parts:
        mask = 0
        for s in p['switches']:
            mask |= 1 << switch_ids.index(s)
        out.append('    { %s, 0x%04X, %s, %s }, // %s' % (p['dl'], mask, 'TRUE' if p['translucent'] else 'FALSE',
                                                          'TRUE' if p['hand'] else 'FALSE', ' '.join(p['textures'])))
    out.append('};')

    pos = m.matrix_positions()
    nmtx = max(pos) + 1 if pos else 1
    out.append('static const f32 ge64_%s_matrix_pos[%d][3] = {' % (ident, nmtx))
    for i in range(nmtx):
        p = pos.get(i, (0.0, 0.0, 0.0))
        out.append('    { %.3ff, %.3ff, %.3ff },' % p)
    out.append('};')
    out.append('extern u8 _ge64_%s_mio0SegmentRomStart[];' % ident)
    out.append('extern u8 _ge64_%s_mio0SegmentRomEnd[];' % ident)
    out.append('static const struct GeGunModel ge64_gun_%s = { ge64_%s_parts, ARRAY_COUNT(ge64_%s_parts), '
               'ge64_%s_matrix_pos, %d, _ge64_%s_mio0SegmentRomStart, _ge64_%s_mio0SegmentRomEnd };'
               % (ident, ident, ident, ident, nmtx, ident, ident))

    open(os.path.join(repo, 'bin', 'ge64_%s.c' % ident), 'w').write('\n'.join(data_out) + '\n')
    open(os.path.join(repo, 'src', 'game', 'ge64_guns', '%s.inc.h' % ident), 'w').write('\n'.join(meta) + '\n')
    print('%s: %d textures, %d vertex arrays, %d parts, %d switches, %d matrices; unsupported: %s'
          % (gun, len(tex_info), len(vtx_offsets), len(parts), len(switch_ids), nmtx, sorted(unknown) or 'none'))

if __name__ == '__main__':
    main(*sys.argv[1:4])
